#!/usr/bin/env bash
# Regression pins for the Git Deploy pre-build-hook root-RCE fix (v2.182.0).
#
# The agent's git_build routes' pre_build_hook (POST /git/pre-build-hook)
# ran a whitelisted-by-literal-string command via `sh -c` directly on the host,
# as root (dockpanel-agent.service carries no User= directive). The whitelist
# blocked shell-injection into the command STRING but did nothing about the
# named commands themselves being standard supply-chain-RCE vectors — every
# one of npm/yarn/pnpm/pip/composer/bundle/cargo runs installer/build hooks
# (package.json postinstall, setup.py, build.rs, ...) that execute arbitrary
# code. An admin arming any one of them for a git deploy caused every
# subsequent repo push AND every transitive dependency to run as root on the
# panel host, unattended. First identified s244, re-verified open at s428
# after 50 sessions during which an audit-coverage blind spot (backend-only
# candidate enumeration, see feedback_dockpanel_audit_scope) kept it off every
# rotation pick.
#
# THE FIX: delete the host-exec route entirely. The same whitelisted string is
# now spliced into the auto-generated Dockerfile's install RUN line
# (auto_generate_dockerfile), so it only ever executes inside the `docker
# build` sandbox every other git deploy on this platform already trusts —
# never a host shell. A design panel scored this against three sandboxing
# alternatives (ephemeral container, privilege-drop via systemd-run, a
# bubblewrap namespace) and it won on containment, fleet-compat, and
# architecture-fit simultaneously: it doesn't add a new isolation boundary
# around the vulnerable execution, it deletes the vulnerable execution path.
#
# Bonus, independently verified: the old code ran pre_build_hook
# UNCONDITIONALLY even after a successful Nixpacks build, silently discarding
# its host-side mutation. The new code skips Nixpacks entirely whenever a
# pre-build command is configured, so the splice always actually lands.
#
# Go port: agent routes panel/go/internal/agent/routes/git_build.go
# (gitBuildAllowedPreBuild, gitBuildAutoDetect), services/git_build.go
# (GitBuildAutoGenerateDockerfile, GitBuildBuildImage); API
# panel/go/internal/api/rt_git_deploys.go (rtGitDeploysPreBuildSpliceMinAgent,
# rtGitDeploysSpawnDeployTask, rtGitDeploysTriggerDeployTask).
#
# These are SOURCE pins and need no running panel.
#   run: bash tests/git-deploy-pre-build-rce-pin-e2e.sh
set -u

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
AGENT_ROUTES="$REPO/panel/go/internal/agent/routes/git_build.go"
AGENT_SVC="$REPO/panel/go/internal/agent/services/git_build.go"
BACKEND="$REPO/panel/go/internal/api/rt_git_deploys.go"
CORE_ROUTER="$REPO/panel/go/internal/api/core_router.go"
for f in "$AGENT_ROUTES" "$AGENT_SVC" "$BACKEND" "$CORE_ROUTER"; do
  [ -f "$f" ] || { echo "missing source file: $f"; exit 1; }
done
FRONTEND="$REPO/panel/frontend/src/pages/GitDeploys.tsx"

PASS=0; FAIL=0
ok()   { PASS=$((PASS+1)); printf '  \033[0;32m✓\033[0m %s\n' "$1"; }
bad()  { FAIL=$((FAIL+1)); printf '  \033[0;31m✗\033[0m %s\n' "$1"; }
has()   { grep -q  -- "$2" "$1" 2>/dev/null && ok "$3" || bad "$3"; }
hasE()  { grep -qE -- "$2" "$1" 2>/dev/null && ok "$3" || bad "$3"; }
hasNot()  { grep -q  -- "$2" "$1" 2>/dev/null && bad "$3" || ok "$3"; }
hasNotE() { grep -qE -- "$2" "$1" 2>/dev/null && bad "$3" || ok "$3"; }
# Comment-blind variants. These two pins describe the retired thing BY NAME in
# the comment that documents why it was retired, so a raw grep would match
# that prose and fail on correct code (the "source-pin PROSE trap").
# Whole-line Go comments only: a trailing-// strip would eat "https://…" strings.
strip_comments() { grep -vE '^[[:space:]]*//' "$1"; }
# Counting grep, not -q: a boolean grep piped from a producer quits at its
# first match and can die of SIGPIPE mid-write, which under `set -o
# pipefail` reads a successful match as a failure (s335). Redirect the count
# away instead — the call site's pass/fail meaning is unchanged.
codeNot() { strip_comments "$1" | grep -c -- "$2" >/dev/null && bad "$3" || ok "$3"; }

echo "== A. the host-exec route is gone, not just hardened =="

codeNot "$AGENT_ROUTES" 'func gitBuildPreBuildHook'     "pre_build_hook handler function no longer exists"
codeNot "$AGENT_ROUTES" 'PreBuildHookRequest struct'    "PreBuildHookRequest struct no longer exists"
has     "$AGENT_ROUTES" 'r.Handle("POST /git/auto-detect"' "positive control: git_build routes are registered in this file"
codeNot "$AGENT_ROUTES" '/git/pre-build-hook"'          "the /git/pre-build-hook route is no longer registered"
has     "$AGENT_ROUTES" 'safecmd.Exec(ctx, "docker", "exec"' "positive control: the detector sees this file's safecmd calls"
N_SH=$(strip_comments "$AGENT_ROUTES" | grep -cE 'safecmd\.[A-Za-z]+\([^,]+, "sh"'); N_SH=${N_SH:-0}
[ "$N_SH" -eq 0 ] && ok "the agent's git_build routes no longer shell out to sh at all" \
  || bad "the agent's git_build routes run sh as a host program again ($N_SH sites)"
codeNot "$BACKEND"      '/git/pre-build-hook"'         "neither backend deploy path still calls /git/pre-build-hook"

echo
echo "== B. the whitelist moved to auto_detect, unchanged content =="

has  "$AGENT_ROUTES" 'var gitBuildAllowedPreBuild = \[\]string{'   "gitBuildAllowedPreBuild whitelist still exists"
N_ENTRIES=$(sed -n '/var gitBuildAllowedPreBuild = \[\]string{/,/^}/p' "$AGENT_ROUTES" 2>/dev/null | grep -c '^\s*"')
if [ "$N_ENTRIES" -eq 9 ]; then
  ok "whitelist still carries exactly its original 9 entries ($N_ENTRIES)"
else
  bad "whitelist entry count drifted: expected 9, found $N_ENTRIES"
fi
hasE "$AGENT_ROUTES" 'if !slices\.Contains\(gitBuildAllowedPreBuild, \*preBuild\)' "gitBuildAutoDetect validates pre_build_cmd against the whitelist before use"
hasE "$AGENT_ROUTES" 'PreBuildCmd \*string +`json:"pre_build_cmd"`'  "the auto-detect request carries the whitelisted override field"
has  "$AGENT_ROUTES" 'func gitBuildAutoDetect('                       "gitBuildAutoDetect handler still exists (whitelist's new home)"

echo
echo "== C. the whitelisted string only ever becomes Dockerfile text =="

hasE "$AGENT_SVC" 'func GitBuildAutoGenerateDockerfile\([^)]*override \*string\)'      "GitBuildAutoGenerateDockerfile takes the override as a parameter"
hasE "$AGENT_SVC" 'func GitBuildAutoGenerateDockerfile\([^)]*\) \(string, bool, \*string, error\)' "GitBuildAutoGenerateDockerfile returns (path, applied, note, err)"
hasE "$AGENT_ROUTES" 'services\.GitBuildAutoGenerateDockerfile\(' "gitBuildAutoDetect still calls GitBuildAutoGenerateDockerfile (route -> service wiring intact)"
has  "$AGENT_SVC" 'func gitBuildNodeInstallRun('   "Node install-line resolver exists"
has  "$AGENT_SVC" 'func gitBuildPipInstallRun('    "Python install-line resolver exists"
has  "$AGENT_SVC" 'corepack enable'       "yarn/pnpm overrides get a corepack prefix (neither is on node:20-alpine's PATH by default)"

echo
echo "== D. mismatch handling: never a broken Dockerfile, never a silent no-op =="

has "$AGENT_SVC" "repo already has a Dockerfile — add the install step as a RUN line there" \
  "a committed Dockerfile refuses to silently absorb an override"
has "$AGENT_SVC" "doesn't apply to this project type — using the default install step" \
  "a cross-language override (e.g. bundle install against Node) falls back to the default, explained"
has "$AGENT_SVC" "has no matching install step for a Go project — ignored" \
  "Go has no gitBuildAllowedPreBuild entry and says so explicitly"
has "$AGENT_SVC" "has no matching install step for a static site — ignored" \
  "a static site has no install step and says so explicitly"

echo
echo "== E. PHP branch: the literal whitelisted string is what actually runs =="

codeNot "$AGENT_SVC" 'composer\.phar'                      "the local composer.phar invocation is gone (was never runnable as the literal 'composer install' string)"
has    "$AGENT_SVC" '\-\-install-dir=/usr/local/bin \-\-filename=composer' "composer is bootstrapped as a global binary so the whitelisted 'composer install' string is really what runs"

echo
echo "== F. build_image: the timeout now covers the folded-in install step, and actually terminates on expiry =="

hasE   "$AGENT_SVC" 'deployRun\(ctx, 900\*time\.Second, [^)]*"docker"' "GitBuildBuildImage's timeout absorbed the old separate 300s pre-build budget (600s -> 900s)"
# Rust's kill_on_drop(true) → Go: deployRun bounds the child with
# context.WithTimeout and spawns it via safecmd.Command(ctx, …), so expiry kills it.
DEPLOY_SVC="$REPO/panel/go/internal/agent/services/deploy.go"
DR=$(strip_comments "$DEPLOY_SVC" | awk '/^func deployRun\(/,/^}/')
if grep -qF 'context.WithTimeout(ctx, timeout)' <<<"$DR" && grep -qF 'safecmd.Command(ctx, bin, args...)' <<<"$DR"; then
  ok "deployRun (GitBuildBuildImage's runner) spawns the docker build under a timeout context — a timed-out build is killed, not orphaned"
else
  bad "deployRun no longer binds the child to a timeout context — a timed-out docker build can orphan past its deadline"
fi

echo
echo "== G. backend: both deploy paths gate on agent version and splice pre_build_cmd through =="

has "$BACKEND" 'const rtGitDeploysPreBuildSpliceMinAgent = "2.182.0"'  "rtGitDeploysPreBuildSpliceMinAgent version gate constant exists"
N_GATE=$(grep -c 'RequireAgentAtLeast(ctx, agent, rtGitDeploysPreBuildSpliceMinAgent,' "$BACKEND" 2>/dev/null); N_GATE=${N_GATE:-0}
if [ "$N_GATE" -ge 2 ]; then
  ok "both deploy paths (interactive + scheduled) call require-agent-at-least with the new gate ($N_GATE call sites)"
else
  bad "expected 2 require-agent-at-least call sites using rtGitDeploysPreBuildSpliceMinAgent, found $N_GATE"
fi
N_SPLICE=$(grep -cE '"pre_build_cmd": +preBuildCmd,' "$BACKEND" 2>/dev/null); N_SPLICE=${N_SPLICE:-0}
if [ "$N_SPLICE" -ge 2 ]; then
  ok "both deploy paths pass pre_build_cmd through to /git/auto-detect ($N_SPLICE call sites)"
else
  bad "expected 2 auto-detect calls carrying pre_build_cmd, found $N_SPLICE"
fi
hasE "$BACKEND" 'func rtGitDeploysSpawnDeployTask\('   "rtGitDeploysSpawnDeployTask (interactive deploy) still exists"
hasE "$BACKEND" 'func rtGitDeploysTriggerDeployTask\(' "rtGitDeploysTriggerDeployTask (scheduled deploy) still exists"

echo
echo "== H. the bonus bug: Nixpacks success no longer silently strands a configured pre-build command =="

N_SKIP=$(grep -cE '^\s*if preBuildCmd == nil \{' "$BACKEND" 2>/dev/null); N_SKIP=${N_SKIP:-0}
N_NIX=$(grep -c '"/git/nixpacks-build"' "$BACKEND" 2>/dev/null); N_NIX=${N_NIX:-0}
if [ "$N_SKIP" -ge 2 ] && [ "$N_NIX" -ge 2 ]; then
  ok "both deploy paths branch on pre_build_cmd before deciding whether to try Nixpacks ($N_SKIP sites, $N_NIX nixpacks calls)"
else
  bad "expected both deploy paths to gate Nixpacks on pre_build_cmd, found $N_SKIP sites / $N_NIX nixpacks calls"
fi

echo
echo "== I. neighboring surfaces are untouched, not silently widened or dropped =="

has "$AGENT_ROUTES" 'func gitBuildHook('                       "gitBuildHook (docker-exec into an already-deployed container) is untouched"
has "$AGENT_ROUTES" 'services.CommandFilterIsSafeHookCommand' "gitBuildHook's char-blacklist gate is untouched"
has "$CORE_ROUTER" 'func isSafeShellCommand(' \
  "the backend's own save-time filter (weaker than gitBuildAllowedPreBuild, shared with post_deploy_cmd) is untouched"

echo
echo "== J. frontend copy no longer promises a host-side effect =="

hasNot "$FRONTEND" 'Runs in the git repo directory before docker build' \
  "the old (now false) 'runs before docker build, on the host' copy is gone"
has    "$FRONTEND" 'Only applies when DockPanel generates the Dockerfile for you' \
  "the field's copy now matches what it actually does"

echo
printf 'passed %d, failed %d\n' "$PASS" "$FAIL"
[ "$FAIL" -eq 0 ]
